// @vitest-environment happy-dom
import { expect, test, vi } from "vitest";
import { renderDiagram } from "./mermaid-render.ts";

test("renders through the isolated frame and accepts only its matching image", async () => {
  const palette = { surface: "#fff", text: "#111", border: "#777", accent: "#070", font: "sans-serif" };
  let frame: HTMLIFrameElement | undefined;
  const append = vi.spyOn(document.body, "append").mockImplementation((...nodes) => {
    frame = nodes[0] as HTMLIFrameElement;
    Object.defineProperty(frame, "contentWindow", { value: window });
  });
  const post = vi.spyOn(window, "postMessage").mockImplementation(() => undefined);
  const result = renderDiagram("graph LR\nA --> B", "diagram-test", palette);
  const controller = new AbortController();
  const cancelled = renderDiagram("graph LR\nA --> C", "diagram-cancelled", palette, controller.signal);
  const rejected = expect(cancelled).rejects.toMatchObject({ name: "AbortError" });
  controller.abort();
  await Promise.resolve();
  expect(frame?.getAttribute("sandbox")).toBe("allow-scripts allow-same-origin");
  expect(frame?.src).toContain("mermaid-frame.html");
  frame?.dispatchEvent(new Event("load"));
  await Promise.resolve();
  await Promise.resolve();
  const message = post.mock.calls[0]?.[0] as { request: number; source: string };
  expect(message.source).toContain("A --> B");
  let settled = false;
  void result.then(() => { settled = true; });
  window.dispatchEvent(new MessageEvent("message", { source: null, data: { request: message.request, image: "data:image/svg+xml;charset=utf-8,spoof" } }));
  window.dispatchEvent(new MessageEvent("message", { source: window, data: { request: message.request + 1, image: "data:image/svg+xml;charset=utf-8,spoof" } }));
  await Promise.resolve();
  expect(settled).toBe(false);
  window.dispatchEvent(new MessageEvent("message", { source: window, data: { request: message.request, image: "data:image/svg+xml;charset=utf-8,%3Csvg%2F%3E" } }));
  await expect(result).resolves.toBe("data:image/svg+xml;charset=utf-8,%3Csvg%2F%3E");
  await rejected;
  expect(post).toHaveBeenCalledTimes(1);
  const invalid = renderDiagram("bad diagram", "diagram-invalid", palette);
  await vi.waitFor(() => expect(post).toHaveBeenCalledTimes(2));
  const invalidRequest = (post.mock.calls[1]?.[0] as { request: number }).request;
  window.dispatchEvent(new MessageEvent("message", { source: window, data: { request: invalidRequest, error: "invalid diagram" } }));
  await expect(invalid).rejects.toThrow("invalid diagram");
  const next = renderDiagram("graph LR\nB --> C", "diagram-next", palette);
  await vi.waitFor(() => expect(post).toHaveBeenCalledTimes(3));
  const nextRequest = (post.mock.calls[2]?.[0] as { request: number }).request;
  window.dispatchEvent(new MessageEvent("message", { source: window, data: { request: nextRequest, image: "data:image/svg+xml;charset=utf-8,%3Csvg%2F%3E" } }));
  await expect(next).resolves.toContain("data:image/svg+xml");
  expect(append).toHaveBeenCalledTimes(1);
  expect(document.querySelector("svg, style")).toBeNull();
  frame?.remove();
  append.mockRestore();
  post.mockRestore();
});
